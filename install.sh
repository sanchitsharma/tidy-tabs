#!/usr/bin/env bash
# Install the Tidy Tabs native messaging host (Claude via the local Claude Code CLI) for Chrome, Dia,
# Phi and Chromium on macOS.
# Usage: ./install.sh [--claude /abs/path/to/claude] [--node /abs/path/to/node]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
HOST_NAME="dev.tidytabs.claude"
HOST_DIR="$ROOT/native-host"
# Runtime copy lives outside ~/Documents: macOS privacy (TCC) blocks browser-spawned helpers from reading it.
RUNTIME_DIR="$HOME/Library/Application Support/tidy-tabs/native-host"
WRAPPER="$RUNTIME_DIR/tidy-tabs-host"
CLAUDE_BIN="" NODE_BIN=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --claude) CLAUDE_BIN="$2"; shift 2 ;;
    --node) NODE_BIN="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

# First real executable on a login-shell PATH, skipping wrapper shims (e.g. cmux) in temp dirs.
resolve() {
  local name="$1" p
  while IFS= read -r p; do
    [[ -z "$p" || "$p" == */cmux-cli-shims/* || "$p" == /var/folders/* || "$p" == /private/var/folders/* ]] && continue
    [[ -x "$p" ]] && { echo "$p"; return 0; }
  done < <(zsh -lc "whence -ap $name" 2>/dev/null; bash -lc "type -ap $name" 2>/dev/null)
  return 1
}
[[ -n "$CLAUDE_BIN" ]] || CLAUDE_BIN="$(resolve claude || true)"
[[ -n "$CLAUDE_BIN" ]] || { [[ -x "$HOME/.local/bin/claude" ]] && CLAUDE_BIN="$HOME/.local/bin/claude"; }
[[ -n "$NODE_BIN" ]] || NODE_BIN="$(resolve node || true)"
[[ -x "$CLAUDE_BIN" ]] || { echo "claude not found; pass --claude /abs/path" >&2; exit 1; }
[[ -x "$NODE_BIN" ]] || { echo "node not found; pass --node /abs/path" >&2; exit 1; }

EXT_ID="$("$NODE_BIN" "$HOST_DIR/extension-id.js" "$ROOT/extension/manifest.json")"

mkdir -p "$RUNTIME_DIR"
cp "$HOST_DIR"/host.js "$HOST_DIR"/claude.js "$HOST_DIR"/framing.js "$HOST_DIR"/logfile.js "$HOST_DIR"/package.json "$RUNTIME_DIR"/
rm -f "$HOST_DIR/tidy-tabs-host"
# Shell-quote every interpolated path (printf %q) so spaces/quotes in paths can't break the wrapper.
Q_CLAUDE="$(printf '%q' "$CLAUDE_BIN")"
Q_NODE="$(printf '%q' "$NODE_BIN")"
Q_HOSTJS="$(printf '%q' "$RUNTIME_DIR/host.js")"
cat > "$WRAPPER" <<WRAP
#!/bin/bash
# Generated by install.sh. Browsers spawn this with a minimal PATH, so everything is absolute.
TIDY_CLAUDE_BIN=$Q_CLAUDE
export TIDY_CLAUDE_BIN
LOGS="\$HOME/Library/Logs/tidy-tabs"
mkdir -p "\$LOGS" 2>/dev/null
# Keep the wrapper's own logs small: past 1000 lines, keep the last 500.
for f in "\$LOGS/host-starts.log" "\$LOGS/host-stderr.log"; do
  if [ -f "\$f" ] && [ "\$(wc -l < "\$f")" -gt 1000 ]; then
    tail -n 500 "\$f" > "\$f.tmp" 2>/dev/null && mv "\$f.tmp" "\$f"
  fi
done
echo "\$(date -u +%FT%TZ) start ppid=\$PPID caller=\$(ps -o comm= -p \$PPID 2>/dev/null)" >> "\$LOGS/host-starts.log" 2>/dev/null
exec $Q_NODE $Q_HOSTJS "\$@" 2>>"\$LOGS/host-stderr.log"
WRAP
chmod 755 "$WRAPPER"

MANIFEST_JSON="$(cat <<JSON
{
  "name": "$HOST_NAME",
  "description": "Tidy Tabs: Claude via local Claude Code CLI",
  "path": "$WRAPPER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
JSON
)"

installed=0
for browser_dir in \
  "$HOME/Library/Application Support/Google/Chrome" \
  "$HOME/Library/Application Support/Dia/User Data" \
  "$HOME/Library/Application Support/com.phibrowser.Mac" \
  "$HOME/Library/Application Support/Chromium"; do
  if [[ -d "$browser_dir" ]]; then
    if [[ "$browser_dir" == *"/Dia/"* && ! -d /Applications/Dia.app && ! -d "$HOME/Applications/Dia.app" ]]; then
      echo "note: Dia user data exists but Dia.app was not found in /Applications; installing the manifest anyway"
    fi
    mkdir -p "$browser_dir/NativeMessagingHosts"
    printf '%s\n' "$MANIFEST_JSON" > "$browser_dir/NativeMessagingHosts/$HOST_NAME.json"
    echo "installed: $browser_dir/NativeMessagingHosts/$HOST_NAME.json"
    installed=$((installed + 1))
  else
    echo "skipped (browser not found): $browser_dir"
  fi
done

# Arc is no longer supported: remove only our own manifest there, nothing else.
ARC_OURS="$HOME/Library/Application Support/Arc/User Data/NativeMessagingHosts/$HOST_NAME.json"
if [[ -f "$ARC_OURS" ]]; then rm -f "$ARC_OURS"; echo "removed old Arc manifest: $ARC_OURS"; fi

echo "extension id: $EXT_ID"
echo "claude: $CLAUDE_BIN"
echo "node:   $NODE_BIN"
[[ $installed -gt 0 ]] || { echo "no browser dirs found" >&2; exit 1; }
echo "Now load $ROOT/extension unpacked (chrome://extensions) and fully restart the browser if it was open."
